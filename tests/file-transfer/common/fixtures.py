"""Reusable test files. Every scenario is (description, filename, expected bytes).

The run token makes the contents specific to one test run.
"""

LARGE_FIXTURE_BYTES = 2 * 1024 * 1024
MIB = 1024 * 1024
SAMPLE_SIZES_MIB = (1, 1, 1, 16)


def smoke_scenarios(run_token):
    """Create one small text file to check that the basic delivery route works."""
    return [
        (
            "small text",
            "payload.txt",
            f"Integration Hub file-transfer smoke test: {run_token}\n".encode(),
        ),
    ]


def functional_scenarios(run_token):
    """Create L2 files that exercise different sizes, contents, and filenames."""
    binary_fixture = run_token.encode() + bytes(range(256)) * 32
    # Trim the generated bytes so the larger file is exactly 2 MiB.
    large_fixture = (
        run_token.encode()
        + bytes(range(256)) * (LARGE_FIXTURE_BYTES // 256 + 1)
    )[:LARGE_FIXTURE_BYTES]
    return [
        ("zero-byte file", "empty.bin", b""),
        ("binary file", "binary-payload.bin", binary_fixture),
        ("2 MiB file", "multi-megabyte.bin", large_fixture),
        (
            "special-character filename",
            "special chars + (1).txt",
            f"Synthetic fixture: {run_token}\n".encode(),
        ),
    ]


def nested_directory_scenarios(run_token):
    """Add directory-handling fixtures for destinations that keep the source key's path.

    The writer must create missing nested directories, keep the source key's
    relative path, and not follow or escape the configured destination prefix.
    """
    return [
        (
            "nested directory file",
            "nested/deeper/payload.txt",
            f"Synthetic nested fixture: {run_token}\n".encode(),
        ),
        (
            "nested special-character directory",
            "folder with spaces/(1) + copy/special-payload.txt",
            f"Synthetic nested special fixture: {run_token}\n".encode(),
        ),
    ]


def performance_scenarios(run_token):
    """Create three 1 MiB samples and one 16 MiB file, totalling 19 MiB.

    Files are synthetic and include the run ID and sample number. Sizes are
    deliberately bounded; this is not a multipart or maximum-size load test.
    """
    scenarios = []
    for index, size_mib in enumerate(SAMPLE_SIZES_MIB, start=1):
        size_bytes = size_mib * MIB
        marker = f"L4 synthetic fixture: {run_token}:{index}\n".encode()
        block = marker + bytes(range(256))
        fixture = (block * (size_bytes // len(block) + 1))[:size_bytes]
        scenarios.append((
            f"{size_mib} MiB sample {index}",
            f"baseline-{index}-{size_mib}mib.bin",
            fixture,
        ))
    return scenarios
