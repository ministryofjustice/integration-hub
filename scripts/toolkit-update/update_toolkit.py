import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

import yaml


UPSTREAM = "ministryofjustice/ai-toolkit"
TOOLKIT_PATH = "toolkits/integration-hub/engineering"
PACKAGE = f"{UPSTREAM}/{TOOLKIT_PATH}"


def commit_sha(value):
    """Require a full Git object ID rather than a branch name or shortened SHA."""
    if not isinstance(value, str) or re.fullmatch(r"[0-9a-f]{40}", value) is None:
        raise ValueError("Expected a full Git commit or tree SHA.")
    return value


def pinned_commit():
    """Read the toolkit's recorded commit, rejecting missing or duplicate entries."""
    lock = yaml.safe_load(Path("apm.lock.yaml").read_text())
    if not isinstance(lock, dict) or not isinstance(lock.get("dependencies"), list):
        raise ValueError("The APM lockfile must contain a dependencies list.")
    matches = [
        dependency for dependency in lock["dependencies"]
        if isinstance(dependency, dict)
        and dependency.get("host") == "github.com"
        and dependency.get("repo_url") == UPSTREAM
        and dependency.get("virtual_path") == TOOLKIT_PATH
    ]
    if len(matches) != 1:
        raise ValueError("Expected exactly one Integration Hub toolkit dependency.")
    return commit_sha(matches[0].get("resolved_commit"))


def github_api(endpoint):
    """Fetch JSON using GitHub CLI authentication; let failures stop the update."""
    result = subprocess.run(
        ["gh", "api", endpoint],
        check=True,
        capture_output=True,
        text=True,
        timeout=60,
    )
    return json.loads(result.stdout)


def upstream_commit():
    """Get the latest commit on the AI toolkit repository's main branch."""
    response = github_api(f"repos/{UPSTREAM}/commits/main")
    if not isinstance(response, dict):
        raise ValueError("GitHub did not return an upstream commit.")
    return commit_sha(response.get("sha"))


def toolkit_tree(commit):
    """Get the Git tree SHA identifying our toolkit directory's contents.

    Equal tree SHAs mean the toolkit is unchanged, even if other parts of the
    upstream repository have changed.
    """
    commit = commit_sha(commit)
    parent, name = TOOLKIT_PATH.rsplit("/", 1)
    entries = github_api(f"repos/{UPSTREAM}/contents/{parent}?ref={commit}")
    if not isinstance(entries, list):
        raise ValueError("GitHub did not return the toolkit parent directory.")
    matches = [
        entry for entry in entries
        if isinstance(entry, dict)
        and entry.get("name") == name
        and entry.get("type") == "dir"
    ]
    if len(matches) != 1:
        raise ValueError(f"Cannot find the engineering toolkit at {commit}.")
    return commit_sha(matches[0].get("sha"))


def prepare_update(body_file, check_only=False):
    """Compare toolkit contents and return whether an update was initially needed.

    Check-only mode makes no changes. Otherwise, update when needed, validate the
    installation, and write the PR description for the workflow's PR action.
    """
    previous = pinned_commit()
    latest = upstream_commit()
    previous_tree = toolkit_tree(previous)
    latest_tree = toolkit_tree(latest)
    changed = previous_tree != latest_tree
    print(f"Pinned commit: {previous}", flush=True)
    print(f"Upstream commit: {latest}", flush=True)
    print(f"Toolkit update needed: {changed}", flush=True)
    if check_only:
        return changed

    if changed:
        subprocess.run(
            ["apm", "update", "--yes", "--target", "copilot", PACKAGE],
            check=True,
            timeout=300,
        )

    # Frozen installation validates the lockfile, including the no-update case.
    subprocess.run(
        ["apm", "install", "--frozen", "--target", "copilot"],
        check=True,
        timeout=300,
    )
    updated = pinned_commit()
    updated_tree = toolkit_tree(updated)
    if updated_tree != toolkit_tree(upstream_commit()):
        raise ValueError(
            "The installed toolkit does not match upstream main. "
            "Upstream may have changed during the run; inspect the APM output and rerun."
        )
    if not changed and updated != previous:
        raise ValueError("Frozen installation unexpectedly changed the toolkit pin.")

    subprocess.run(["git", "diff", "--check"], check=True, timeout=30)
    body_file.write_text(
        "This pull request body was generated by GitHub Copilot.\n\n"
        "## Summary\n\n"
        "Update the Integration Hub AI toolkit to the latest upstream guidance.\n\n"
        f"- Previous revision: `{previous}`\n"
        f"- Updated revision: `{updated}`\n"
        f"- [Upstream changes](https://github.com/{UPSTREAM}/compare/{previous}...{updated})\n"
        f"- [Toolkit at the updated revision](https://github.com/{UPSTREAM}/tree/{updated}/{TOOLKIT_PATH})\n\n"
        "Only the APM manifest and lockfile are included; generated instructions stay local.\n"
        "Review the toolkit changes before merging. This PR does not auto-merge.\n\n"
        "## Testing\n\n"
        "- Updater unit tests passed in the workflow.\n"
        "- `apm install --frozen --target copilot` passed.\n"
        "- Installed toolkit contents match upstream main at validation time.\n"
        "- `git diff --check` passed.\n"
        "- Application and live AWS tests were not run for this toolkit-only update.\n"
    )
    return changed


def main():
    """Parse command-line options and report failures with a nonzero exit status."""
    parser = argparse.ArgumentParser(description="Prepare a reviewed AI toolkit update.")
    parser.add_argument("--body-file", type=Path)
    parser.add_argument(
        "--check-only", action="store_true",
        help="Compare upstream without installing dependencies or changing files.",
    )
    args = parser.parse_args()
    if not args.check_only and args.body_file is None:
        parser.error("--body-file is required unless --check-only is used")
    try:
        prepare_update(args.body_file, args.check_only)
    except subprocess.CalledProcessError as error:
        print(
            f"Toolkit update failed: {error.cmd[0]} exited with status {error.returncode}.",
            file=sys.stderr,
        )
        if error.stderr:
            print(error.stderr, file=sys.stderr)
        return 1
    except (OSError, ValueError, yaml.YAMLError, subprocess.TimeoutExpired) as error:
        print(f"Toolkit update failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
